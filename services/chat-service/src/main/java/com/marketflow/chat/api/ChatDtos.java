package com.marketflow.chat.api;

import com.fasterxml.jackson.databind.JsonNode;
import com.marketflow.chat.domain.MessageType;
import jakarta.validation.constraints.Max;
import jakarta.validation.constraints.Min;
import jakarta.validation.constraints.NotBlank;
import jakarta.validation.constraints.NotNull;
import jakarta.validation.constraints.Size;

import java.math.BigDecimal;
import java.time.Instant;
import java.util.List;
import java.util.UUID;

public final class ChatDtos {

    private ChatDtos() {
    }

    // ---------- requests (REST) ----------

    /** Start a conversation with a shop, or get the existing one for the same context. */
    public record StartConversationRequest(@NotNull UUID vendorId, UUID productId, UUID suborderId) {
    }

    /**
     * @param clientMessageId generated by the client per message and reused on every retry (idempotency key)
     * @param body            text, or the caption of an image; the length limit is checked by the content policy
     * @param attachmentId    IMAGE: an attachment uploaded to this conversation
     * @param productId       PRODUCT_CARD: a product of this conversation's shop
     * @param suborderId      ORDER_CARD: the buyer's suborder with this shop
     */
    public record SendMessageRequest(@NotNull UUID clientMessageId, @NotNull MessageType type,
                                     @Size(max = 8000) String body, UUID attachmentId, UUID productId,
                                     UUID suborderId) {
    }

    public record EditMessageRequest(@NotBlank @Size(max = 8000) String body) {
    }

    /** @param lastReadMessageId the newest message the reader has seen; omitted means "everything so far" */
    public record ReadRequest(@Min(0) Long lastReadMessageId) {
    }

    public record MuteRequest(boolean muted) {
    }

    public enum ReportReason { SPAM, SCAM, ABUSE, OFF_PLATFORM_PAYMENT, OTHER }

    public record ReportRequest(@NotNull ReportReason reason, @Size(max = 1000) String details) {
    }

    public enum ReportAction { DISMISS, BLOCK_CONVERSATION }

    public record ResolveReportRequest(@NotNull ReportAction action, @Size(max = 1000) String note) {
    }

    public record QuickReplyRequest(@NotBlank @Size(max = 60) String title, @NotBlank @Size(max = 1000) String body,
                                    @Min(0) @Max(1000) Integer sortOrder) {
    }

    // ---------- STOMP frames (client → server) ----------

    public record SendFrame(UUID conversationId, UUID clientMessageId, MessageType type, String body,
                            UUID attachmentId, UUID productId, UUID suborderId) {
        public SendMessageRequest toRequest() {
            return new SendMessageRequest(clientMessageId, type, body, attachmentId, productId, suborderId);
        }
    }

    public record TypingFrame(UUID conversationId, boolean typing) {
    }

    public record ReadFrame(UUID conversationId, Long lastReadMessageId) {
    }

    // ---------- views ----------

    public record MessageView(long id, UUID conversationId, UUID senderId, String senderRole, String type, String body,
                              String attachmentUrl, JsonNode metadata, UUID clientMessageId, Instant createdAt,
                              Instant editedAt, boolean deleted) {
    }

    /**
     * The other side as seen by the viewer. For a buyer it is the shop (all of its seller accounts); for the
     * shop it is the buyer.
     *
     * @param userIds             accounts on that side, used to match live presence events
     * @param typicalReplySeconds the shop's median first-reply time (null for buyers, or too few answers yet)
     */
    public record CounterpartView(String kind, String name, UUID vendorId, String vendorSlug, List<UUID> userIds,
                                  boolean online, Instant lastSeenAt, Integer typicalReplySeconds) {
    }

    /** What the conversation is about. kind: PRODUCT, ORDER or GENERAL. */
    public record ContextView(String kind, UUID productId, String productName, String productImageUrl,
                              BigDecimal price, String currency, UUID orderId, UUID suborderId, String orderStatus,
                              String itemsSummary, BigDecimal orderTotal) {
    }

    /**
     * @param side                   the viewer's side (BUYER, VENDOR) or null for an administrator
     * @param theirLastReadMessageId the furthest the other side has read: messages up to it show as "seen"
     */
    public record ConversationView(UUID id, String side, String status, UUID buyerId, String buyerName,
                                   UUID vendorId, String vendorName, ContextView context,
                                   CounterpartView counterpart, long myLastReadMessageId,
                                   long theirLastReadMessageId, boolean muted, boolean canWrite, Instant createdAt,
                                   Instant lastMessageAt) {
    }

    public record MessagePreview(long id, String type, String text, String senderRole, boolean deleted) {
    }

    public record ConversationSummary(UUID id, String status, CounterpartView counterpart, ContextView context,
                                      MessagePreview lastMessage, int unread, boolean muted, Instant lastMessageAt) {
    }

    /** Keyset page: pass {@code nextCursor} back as {@code cursor}; null means there is nothing more. */
    public record CursorPage<T>(List<T> items, String nextCursor) {
    }

    /**
     * @param items   oldest first
     * @param hasMore more messages exist beyond this page in the requested direction
     * @param changed (after= requests only) messages edited or deleted since the client last synced
     */
    public record MessagePage(List<MessageView> items, boolean hasMore, List<MessageView> changed) {
    }

    public record StartResult(ConversationView conversation, boolean created) {
    }

    public record UnreadCounts(int asBuyer, int asVendor) {
    }

    public record AttachmentView(UUID id, String url, String contentType, int sizeBytes) {
    }

    public record ReportView(UUID id, UUID conversationId, UUID reporterId, String reporterSide, String reason,
                             String details, String status, String resolution, String resolutionNote,
                             UUID resolvedBy, Instant resolvedAt, Instant createdAt, String vendorName,
                             String buyerName, int violations) {
    }

    public record AdminConversationSummary(UUID id, String status, UUID buyerId, String buyerName, UUID vendorId,
                                           String vendorName, ContextView context, int messages, int openReports,
                                           int violations, Instant lastMessageAt) {
    }

    public record AdminConversationDetail(ConversationView conversation, List<ReportView> reports, int violations) {
    }

    public record QuickReplyView(UUID id, String title, String body, int sortOrder) {
    }

    // ---------- events pushed to sockets (server → client) ----------

    /** /user/queue/messages. kind: MESSAGE_CREATED, MESSAGE_UPDATED, CONVERSATION_UPDATED */
    public record MessageEvent(String kind, UUID conversationId, MessageView message, String conversationStatus) {
    }

    /** /user/queue/typing */
    public record TypingEvent(UUID conversationId, String side, String name, boolean typing) {
    }

    /** /user/queue/receipts: the reader's side has read everything up to lastReadMessageId */
    public record ReceiptEvent(UUID conversationId, String side, long lastReadMessageId) {
    }

    /** /user/queue/presence */
    public record PresenceEvent(UUID userId, boolean online, Instant lastSeenAt) {
    }

    /** /user/queue/errors, to the session that sent the failing frame only */
    public record ErrorEvent(String code, String message, UUID conversationId, UUID clientMessageId) {
    }
}
